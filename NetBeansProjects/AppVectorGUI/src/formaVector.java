    private void checkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkActionPerformed
        int val = 0;
        boolean band = true;

        try {
            val = Integer.parseInt(this.check.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Inserta un numero", "Entrada no valida", JOptionPane.WARNING_MESSAGE);
            check.requestFocus();
            band = false;
        }

        if (band == true) {
            modeloTabla.insertRow(modeloTabla.getRowCount(), new Object[]{val});

        }
        check.setText("");
        check.requestFocus();

    }//GEN-LAST:event_checkActionPerformed

    private void btnMayorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMayorActionPerformed
        vector = new CVector(modeloTabla.getRowCount());

        for (int i = 0; i < vector.tam(); i++) {
            vector.asignar((int) modeloTabla.getValueAt(i, 0), i);
        }

        lblMayor.setText("" + vector.mayor());

    }//GEN-LAST:event_btnMayorActionPerformed

