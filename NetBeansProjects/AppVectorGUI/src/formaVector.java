    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (!check.getText().equals("")) {
            modeloTabla.setValueAt(this.check.getText(), jTable1.getSelectedRow(), 0);
        } else {
            JOptionPane.showMessageDialog(null, "Inserta un valor", "Entrada no valida", JOptionPane.INFORMATION_MESSAGE);
            check.requestFocus();
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnRandomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRandomActionPerformed

        Random rd = new Random();

        modeloTabla.setRowCount(rd.nextInt(5, 10));
        for (int r = 0; r < modeloTabla.getRowCount(); r++) {
            modeloTabla.setValueAt(rd.nextInt(100, 1000), r, 0);
        }
    }//GEN-LAST:event_btnRandomActionPerformed

