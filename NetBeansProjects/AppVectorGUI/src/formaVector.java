    private void invertirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_invertirActionPerformed

        vector = new CVector(modeloTabla.getRowCount());

        for (int i = 0; i < vector.tam(); i++) {
            double val = Double.parseDouble(modeloTabla.getValueAt(i, 0).toString());
            vector.asignar((int) val, i);
        }

        modeloTabla.setRowCount(0);
        
        CVector invertido = vector.invertir();

        for (int i = 0; i < invertido.tam(); i++) {
            modeloTabla.addRow(new Object[]{(int)invertido.leer(i)});
        }
    }//GEN-LAST:event_invertirActionPerformed

