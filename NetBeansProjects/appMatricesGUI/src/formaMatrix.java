    private void btnDiagPrinActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDiagPrinActionPerformed
        int sum = 0;
        if (tablaPrin.getRowCount() == tablaPrin.getColumnCount()) {
            for (int i = 0, j = 0; i < matriz.length; i++, j++) {
                sum += matriz[i][j];
            }
            promDiagPrin.setText(String.format("%.2f", (double) sum / matriz.length));
        }
    }//GEN-LAST:event_btnDiagPrinActionPerformed

    private void rbDefaultActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rbDefaultActionPerformed
        spinRengs.setValue(3);
        spinCols.setValue(3);
        
        matriz = new int[][]{{1,2,3},{4,5,6},{7,8,9}};
        
        rellenar(matriz);
    }//GEN-LAST:event_rbDefaultActionPerformed

    private void rbRandomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rbRandomActionPerformed
        Random rd = new Random();
        matriz = new int [modeloTabla.getRowCount()][modeloTabla.getColumnCount()];
        for (int i = 0; i < matriz.length; i++) {
            for (int j = 0; j < matriz[0].length; j++) {
                matriz[i][j] = rd.nextInt(10,100);
            }
        }
        
        rellenar(matriz);
    }//GEN-LAST:event_rbRandomActionPerformed

    private void btnDiagSecActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDiagSecActionPerformed
        int sum = 0;
        if (tablaPrin.getRowCount() == tablaPrin.getColumnCount()) {
            for (int i = 0, j = matriz.length - 1; j >= 0; i++, j--) {
                sum += matriz[i][j];
            }
            promDiagSec.setText(String.format("%.2f", (double) sum / matriz.length));
        }
    }//GEN-LAST:event_btnDiagSecActionPerformed

