    public void rellenar(int [][] relleno){
        for (int i = 0; i < relleno.length; i++) {
            for (int j = 0; j < relleno[0].length; j++) {
                modeloTabla.setValueAt(relleno[i][j], i, j);
            }
        }
        paresNones(relleno);
    }
    
    public void paresNones(int[][] mat) {
        nones = new int[modeloTabla.getRowCount()];
        pares = new int[modeloTabla.getColumnCount()];

        for (int r = 0; r < mat.length; r++) {
            for (int c = 0; c < mat[0].length; c++) {
                if (mat[r][c] % 2 != 0) {
                    nones[r]++;
                } else {
                    pares[c]++;
                }
            }
        }
    }
    
    
    
    
